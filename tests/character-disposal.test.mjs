import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../game.js',import.meta.url),'utf8');
const begin=source.indexOf('function disposeCharacterMesh(');
const end=source.indexOf('\nfunction disposeGooseMesh(',begin);
assert.ok(begin>=0&&end>begin,'character cleanup helper exists');
assert.match(source,/if\(mate\)disposeCharacterMesh\(mate\)/,'restart disposes teammate');
assert.match(source,/function disposeGooseMesh\(goose\)\{disposeCharacterMesh\(goose\)\}/,'goose cleanup retains disposal');
const removed=[];
const scene={remove:object=>removed.push(object)};
const context=vm.createContext({S:scene,Set});
vm.runInContext(source.slice(begin,end),context);
const geometry={count:0,dispose(){this.count++}};
const material={count:0,dispose(){this.count++}};
const character={traverse(fn){fn({isMesh:true,geometry,material});fn({isMesh:true,geometry,material:[material]})}};
context.disposeCharacterMesh(character);
assert.equal(removed.length,1);
assert.equal(removed[0],character);
assert.equal(geometry.count,1,'shared geometry disposed once');
assert.equal(material.count,1,'shared material disposed once');
console.log('Character GPU cleanup regression passed');
